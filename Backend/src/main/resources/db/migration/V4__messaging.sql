-- FR-15 messaging. One conversation model for every chat type.
-- ASSOCIATION / PROJECT / DEPARTMENT audiences are derived live from memberships and
-- the project team; GROUP and DIRECT conversations list their members explicitly.
-- scope_key makes built-in conversations unique per scope (portable across H2/PostgreSQL):
--   ASSOCIATION:{associationId}, PROJECT:{projectId}, DEPARTMENT:{departmentId},
--   DIRECT:{associationId}:{lowerUserId}:{higherUserId}, GROUP:{conversationId}.
CREATE TABLE conversations (
    id UUID PRIMARY KEY,
    association_id UUID NOT NULL REFERENCES associations(id) ON DELETE CASCADE,
    type VARCHAR(20) NOT NULL CHECK (type IN ('ASSOCIATION', 'PROJECT', 'DEPARTMENT', 'GROUP', 'DIRECT')),
    scope_key VARCHAR(200) NOT NULL UNIQUE,
    project_id UUID REFERENCES projects(id),
    department_id UUID,
    name VARCHAR(100),
    created_by_user_id UUID REFERENCES app_users(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    FOREIGN KEY (project_id, department_id) REFERENCES project_departments(project_id, id),
    CHECK (type <> 'PROJECT' OR (project_id IS NOT NULL AND department_id IS NULL)),
    CHECK (type <> 'DEPARTMENT' OR (project_id IS NOT NULL AND department_id IS NOT NULL)),
    CHECK (type NOT IN ('ASSOCIATION', 'GROUP', 'DIRECT') OR (project_id IS NULL AND department_id IS NULL)),
    CHECK ((type = 'GROUP' AND name IS NOT NULL) OR (type <> 'GROUP' AND name IS NULL))
);
CREATE INDEX conversations_association_idx ON conversations(association_id, type);

CREATE TABLE conversation_members (
    conversation_id UUID NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
    user_id UUID NOT NULL REFERENCES app_users(id),
    -- Nulled when the person leaves the association: access requires a live membership,
    -- and rejoining (a new membership row) does not silently revive old group access.
    association_membership_id UUID REFERENCES association_memberships(id) ON DELETE SET NULL,
    added_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (conversation_id, user_id)
);
CREATE INDEX conversation_members_user_idx ON conversation_members(user_id);

CREATE TABLE messages (
    seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id UUID NOT NULL UNIQUE,
    conversation_id UUID NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
    sender_user_id UUID NOT NULL REFERENCES app_users(id),
    body VARCHAR(4000) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX messages_conversation_seq_idx ON messages(conversation_id, seq);
